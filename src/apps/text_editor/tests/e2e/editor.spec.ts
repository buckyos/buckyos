  await expect(page.locator('.preview-pane')).toHaveAttribute('data-status', 'ready')
  await expect(page.getByRole('tab', { name: /binary\.bin/ })).toBeVisible()
  // A known media type goes to Preview without downloading it; an unknown extension is judged by its bytes.
  await files.getByRole('option', { name: 'photo.png' }).dblclick()
  await expect(page.frameLocator('.preview-pane iframe').getByTestId('fake-preview')).toHaveAttribute('data-path', '/home/test-user/notes/photo.png')
