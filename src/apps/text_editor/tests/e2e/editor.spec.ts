  await page.request.post('http://127.0.0.1:3260/test/modify', { data: { path: '/home/test-user/notes/photo.png', text: 'PNG not really' } })
  await page.request.post('http://127.0.0.1:3260/test/modify', { data: { path: '/home/test-user/notes/data.unknownext', text: 'plain words in an unknown extension' } })
  await open(page)
