  await expect(diff.getByTestId('goal-diff-constraints')).toHaveCount(0)

  // Leaving the timetable alone and changing nothing writes nothing.
  await gates.getByTestId('gate-edit').click()
  await gates.getByTestId('gate-form').getByRole('button', { name: 'Save' }).click()
  await expect(gates.getByTestId('gate-result')).toContainText('nothing changed')
