test('activate appends a manual activation that the detail and the home list show', async ({ page }) => {
  await open(page, `#/goal/${TIDY}`)
  const activations = page.getByTestId('goal-activations')
  await expect(activations.getByTestId('activation-row')).toHaveCount(3)
  await page.getByTestId('goal-operations').getByRole('button', { name: 'Activate' }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toContainText('Activate “Keep Downloads tidy” now?')
  await dialog.getByLabel('Reason (optional)').fill('check now')
  await dialog.getByRole('button', { name: 'Activate' }).click()
  await expect(dialog).toBeHidden()
  await expect(page.getByTestId('goal-operation-result')).toContainText('activation posted at index')
  await expect(activations.getByTestId('activation-row')).toHaveCount(4)
  const latest = activations.locator('[data-testid="activations-epoch-2"]').getByTestId('activation-row').first()
  await expect(latest).toContainText('manual')
  await expect(latest).toContainText('check now')
  await expect(latest).toContainText('No action')
  await expect(page.getByTestId('goal-summary')).toContainText('No action')

  await page.getByRole('link', { name: '← Goals' }).click()
  await expect(page.getByTestId(`goal-${TIDY}`).getByTestId('goal-last-activation')).toContainText('just now · No action')
})

test('pause shows a paused gate and resume restores it', async ({ page }) => {
  await open(page, `#/goal/${BUILTIN}`)
  const ops = page.getByTestId('goal-operations')
  await ops.getByRole('button', { name: 'Pause' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('button', { name: 'Cancel' }).click()
  await expect(dialog).toBeHidden()
  await expect(page.getByTestId('goal-header')).toContainText('Active')

  await ops.getByRole('button', { name: 'Pause' }).click()
  await dialog.getByLabel('Reason (optional)').fill('travelling')
  await dialog.getByRole('button', { name: 'Pause' }).click()
  await expect(page.getByTestId('goal-operation-result')).toContainText('status is now Paused')
  await expect(page.getByTestId('goal-header')).toContainText('Paused')
  await expect(page.getByTestId('goal-summary')).toContainText('(gate paused)')
  await expect(page.getByTestId('goal-summary')).toContainText('Last skip: paused')
  await expect(page.getByTestId('goal-maintenance')).toContainText('paused')
  await expect(ops.getByRole('button', { name: 'Pause' })).toHaveCount(0)
  await expect(ops.getByRole('button', { name: 'Archive' })).toBeDisabled()
  await expect(page.getByTestId('goal-definition')).toContainText('travelling')

  await ops.getByRole('button', { name: 'Resume' }).click()
  await dialog.getByRole('button', { name: 'Resume' }).click()
  await expect(page.getByTestId('goal-operation-result')).toContainText('status is now Active')
  await expect(page.getByTestId('goal-header')).toContainText('Active')
  await expect(page.getByTestId('goal-summary')).toContainText('(gate no_change)')
  await expect(ops.getByRole('button', { name: 'Pause' })).toBeVisible()
  await expect(page.getByTestId('goal-changes').getByTestId('change-row')).toHaveCount(3)
})

test('an archived goal offers reopen and a live one archive with a reason', async ({ page }) => {
  await open(page, `#/goal/${ARCHIVED}`)
  const ops = page.getByTestId('goal-operations')
  await expect(ops.getByRole('button', { name: 'Activate' })).toHaveCount(0)
  await expect(ops.getByRole('button', { name: 'Archive' })).toHaveCount(0)
  await ops.getByRole('button', { name: 'Reopen' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('button', { name: 'Reopen' }).click()
  await expect(dialog.getByRole('alert')).toContainText('A reason is required')
  await dialog.getByLabel('Reason', { exact: true }).fill('new photos arrived')
  await dialog.getByLabel('Start with a fresh state').check()
  await dialog.getByRole('button', { name: 'Reopen' }).click()
  await expect(page.getByTestId('goal-operation-result')).toContainText('epoch 2 opened')
  await expect(page.getByTestId('goal-header')).toContainText('Active')
  await expect(page.getByTestId('goal-definition').getByTestId('goal-epoch-2')).toContainText('reopened')

  await ops.getByRole('button', { name: 'Archive' }).click()
  await dialog.getByLabel('Reason', { exact: true }).fill('done for good')
  await dialog.getByRole('button', { name: 'Archive' }).click()
  await expect(page.getByTestId('goal-operation-result')).toContainText('status is now Archived')
  await expect(page.getByTestId('goal-header')).toContainText('Archived')
  await expect(ops.getByRole('button', { name: 'Reopen' })).toBeVisible()
})

