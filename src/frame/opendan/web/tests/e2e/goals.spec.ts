  await expect(form.getByRole('alert')).toContainText('Check every (seconds, at least 60): a whole number of at least 60')
  await form.getByLabel('Check every (seconds, at least 60)').fill('3600')
  await form.getByRole('button', { name: 'Save' }).click()

  await expect(gates.getByTestId('gate-result')).toContainText('budget and schedule saved (revision 3)')
  await expect(form).toHaveCount(0)
  await expect(gates.getByTestId('gate-interval')).toHaveText('30m')
