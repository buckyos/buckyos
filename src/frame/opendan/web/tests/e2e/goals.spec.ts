test('pause records a paused skip and resume restores it', async ({ page }) => {
  await open(page, `#/goal/${BUILTIN}`)
  const ops = page.getByTestId('goal-operations')
  await ops.getByRole('button', { name: 'Sleep' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('button', { name: 'Cancel' }).click()
  await expect(dialog).toBeHidden()
  await expect(page.getByTestId('goal-header')).toContainText('Active')

  await ops.getByRole('button', { name: 'Sleep' }).click()
  await dialog.getByLabel('Reason (optional)').fill('travelling')
  await dialog.getByRole('button', { name: 'Sleep' }).click()
  await expect(page.getByTestId('goal-operation-result')).toContainText('status is now Dormant')
  await expect(page.getByTestId('goal-header')).toContainText('Dormant')
  await expect(page.getByTestId('goal-summary')).toContainText('Last skip: paused')
  await expect(ops.getByRole('button', { name: 'Sleep' })).toHaveCount(0)
  await expect(ops.getByRole('button', { name: 'Archive' })).toBeDisabled()
  await expect(page.getByTestId('goal-definition')).toContainText('travelling')

  await ops.getByRole('button', { name: 'Wake' }).click()
  await dialog.getByRole('button', { name: 'Wake' }).click()
  await expect(page.getByTestId('goal-operation-result')).toContainText('status is now Active')
  await expect(page.getByTestId('goal-header')).toContainText('Active')
  await expect(page.getByTestId('goal-summary')).toContainText('(check false)')
  await expect(ops.getByRole('button', { name: 'Sleep' })).toBeVisible()
  await expect(page.getByTestId('goal-changes').getByTestId('change-row')).toHaveCount(3)
})

test('an archived goal offers reopen and a live one archive with a reason', async ({ page }) => {
  await open(page, `#/goal/${ARCHIVED}`)
  const ops = page.getByTestId('goal-operations')
  await expect(ops.getByRole('button', { name: 'Activate' })).toHaveCount(0)
  await expect(ops.getByRole('button', { name: 'Archive' })).toHaveCount(0)
  await ops.getByRole('button', { name: 'Reopen' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('button', { name: 'Reopen' }).click()
  await expect(dialog.getByRole('alert')).toContainText('A reason is required')
  await dialog.getByLabel('Reason', { exact: true }).fill('new photos arrived')
  await dialog.getByLabel('Start with a fresh state').check()
  await dialog.getByRole('button', { name: 'Reopen' }).click()
  await expect(page.getByTestId('goal-operation-result')).toContainText('epoch 2 opened')
  await expect(page.getByTestId('goal-header')).toContainText('Active')
  await expect(page.getByTestId('goal-definition').getByTestId('goal-epoch-2')).toContainText('reopened')

  await ops.getByRole('button', { name: 'Archive' }).click()
  await dialog.getByLabel('Reason', { exact: true }).fill('done for good')
  await dialog.getByRole('button', { name: 'Archive' }).click()
  await expect(page.getByTestId('goal-operation-result')).toContainText('status is now Archived')
  await expect(page.getByTestId('goal-header')).toContainText('Archived')
  await expect(ops.getByRole('button', { name: 'Reopen' })).toBeVisible()
})

