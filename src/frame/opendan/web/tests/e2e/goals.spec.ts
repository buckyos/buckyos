import { expect, test, type Page } from '@playwright/test'

const BUILTIN = 'goal-memory-maintenance'
const TIDY = 'goal-downloads-tidy'
const ARCHIVED = 'goal-photo-backlog'

const open = async (page: Page, hash = '') => {
  const errors: string[] = []
  page.on('pageerror', (e) => errors.push(e.message))
  await page.goto(`/?data=mock&lang=en${hash}`)
  await expect(page.getByTestId('data-source')).toHaveText('data: mock')
  return errors
}

test('home lists every goal with its activation, next opportunity and skip reason', async ({ page }) => {
  const errors = await open(page)
  const goals = page.getByTestId('goals')
  await expect(goals.getByRole('listitem')).toHaveCount(3)
  // Active goals first, the archived one last.
  const ids = await goals.getByRole('listitem').evaluateAll((items) => items.map((li) => li.getAttribute('data-testid')))
  expect(ids[2]).toBe(`goal-${ARCHIVED}`)

  const builtin = goals.getByTestId(`goal-${BUILTIN}`)
  await expect(builtin).toContainText('Memory maintenance')
  await expect(builtin.getByTestId('goal-builtin')).toHaveText('Built-in')
  await expect(builtin).toContainText('Active · Maintain')
  await expect(builtin.getByTestId('goal-last-activation')).toContainText('1 h ago · Acted')
  await expect(builtin.getByTestId('goal-next')).toContainText(/Next opportunity: \d\d:\d\d:\d\d \(gate no_change\)/)
  await expect(builtin.getByTestId('goal-skip')).toContainText('Last skip: no_change')
  await expect(builtin.getByTestId('goal-candidates')).toContainText('1 candidates awaiting confirmation')
  await expect(builtin.getByRole('link')).toHaveAttribute('href', `#/goal/${BUILTIN}`)

  const tidy = goals.getByTestId(`goal-${TIDY}`)
  await expect(tidy.getByTestId('goal-builtin')).toHaveCount(0)
  await expect(tidy.getByTestId('goal-last-activation')).toContainText('Needs info')
  await expect(tidy.getByTestId('goal-skip')).toContainText('min_interval')
  await expect(tidy.getByTestId('goal-next')).not.toContainText('gate')

  const archived = goals.getByTestId(`goal-${ARCHIVED}`)
  await expect(archived).toContainText('Archived · Achieve')
  await expect(archived.getByTestId('goal-next')).toContainText('Manual and event driven only')
  await expect(archived.getByTestId('goal-error')).toContainText('529 (overloaded)')
  expect(errors).toEqual([])
})

test('goal detail groups activations by epoch and links to the session detail', async ({ page }) => {
  const errors = await open(page)
  await page.getByTestId(`goal-${TIDY}`).getByRole('link').click()
  await expect(page.getByTestId('goal-header')).toContainText('Keep Downloads tidy')
  await expect(page.getByTestId('goal-header')).toContainText('Active')
  await expect(page.getByTestId('goal-builtin-info')).toHaveCount(0)

  const definition = page.getByTestId('goal-definition')
  await expect(definition).toContainText('Keep PDFs')
  await expect(definition).toContainText('every 6h')
  await expect(definition).toContainText('workspace:ws-downloads')
  await expect(definition.getByTestId('goal-epoch-2')).toContainText('restarted')
  await definition.getByLabel('Revision').selectOption('1')
  await expect(definition).not.toContainText('Keep PDFs')
  await expect(definition).toContainText('1 / 2')

  const state = page.getByTestId('goal-state')
  await expect(state).toContainText('3 stale installers remain')
  await expect(state).toContainText('whether the .dmg files')
  await expect(state.getByTestId('goal-question')).toContainText('ntf-4a1b')
  await expect(state.getByTestId('goal-usage')).toContainText('12.8k / 300k (287k remaining)')

  const activations = page.getByTestId('goal-activations')
  await expect(activations.getByTestId('activation-row')).toHaveCount(3)
  const epochs = activations.locator('[data-testid^="activations-epoch-"]')
  await expect(epochs).toHaveCount(2)
  await expect(epochs.first()).toContainText('Epoch 2')
  await expect(epochs.first().getByTestId('activation-row')).toHaveCount(1)
  await expect(epochs.first()).toContainText('needs_input')
  await expect(epochs.first()).toContainText('Needs info')
  await expect(epochs.last().getByTestId('activation-row')).toHaveCount(2)
  await expect(epochs.last().getByTestId('activation-row').first()).toContainText('Work finished: succeeded')
  await expect(epochs.last()).toContainText('1 runs · 5.1k')
  await expect(page.getByTestId('goal-changes').getByTestId('change-row')).toHaveCount(4)
  await expect(page.getByTestId('goal-maintenance')).toHaveCount(0)

  await epochs.first().getByTestId('activation-row').getByRole('link', { name: `${TIDY}-e2` }).click()
  await expect(page).toHaveURL(new RegExp(`#/session/${TIDY}-e2$`))
  await expect(page.getByTestId('session-summary')).toContainText('Keep Downloads tidy')
  await expect(page.getByTestId('session-summary')).toContainText('Epoch 2')
  expect(errors).toEqual([])
})

