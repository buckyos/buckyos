export type TextKey = keyof typeof en

const requested = new URLSearchParams(window.location.search).get('lang')
export const lang: 'zh' | 'en' =
  requested === 'zh' || requested === 'en' ? requested : navigator.language.toLowerCase().startsWith('zh') ? 'zh' : 'en'

const dict = lang === 'zh' ? zh : en

export const t = (key: TextKey, vars?: Record<string, string | number>): string =>
  dict[key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars?.[name] ?? ''))

export const ago = (ms?: number | null): string => {
  if (!ms) return ''
  const s = Math.max(0, Math.round((Date.now() - ms) / 1000))
  if (s < 60) return t('justNow')
  if (s < 3600) return t('minutesAgo', { n: Math.floor(s / 60) })
  if (s < 86400) return t('hoursAgo', { n: Math.floor(s / 3600) })
  return t('daysAgo', { n: Math.floor(s / 86400) })
}
