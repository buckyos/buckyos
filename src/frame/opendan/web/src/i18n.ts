export type TextKey = keyof typeof en

const packs = import.meta.glob<Partial<typeof en>>('./locales/*.json', { import: 'default' })

const listeners = new Set<() => void>()
const loaded = new Map<SupportedLocale, Partial<typeof en>>([['en', en], ['zh-CN', zh]])
export let lang: SupportedLocale = 'en'
let requested: SupportedLocale = 'en'
let dict: Partial<typeof en> = en

export const subscribeLanguage = (listener: () => void) => {
  listeners.add(listener)
  return () => { listeners.delete(listener) }
}
export const currentLanguage = () => lang

export async function setLanguage(value: string) {
  const locale = matchSupportedLocale(value) ?? 'en'
  requested = locale
  let table = loaded.get(locale)
  if (!table) {
    try {
      table = await packs[`./locales/${locale}.json`]()
      loaded.set(locale, table)
    } catch {
      table = en
    }
  }
  if (requested !== locale) return
  lang = table === en ? 'en' : locale
  dict = table
  document.documentElement.lang = lang
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr'
  listeners.forEach((listener) => listener())
}

const queryLang = new URLSearchParams(window.location.search).get('lang')
export const initialLanguage = setLanguage(matchSupportedLocale(queryLang) ?? browserLocale())

export const t = (key: TextKey, vars?: Record<string, string | number>): string =>
  (dict[key] ?? en[key]).replace(/\{(\w+)\}/g, (_, name: string) => String(vars?.[name] ?? ''))

