test('custom provider rules use structured model editing and whole-file JSON preview', async ({ page }, testInfo) => {
  await page.addInitScript(() => localStorage.setItem('buckyos.prototype.locale.v1', 'en'))
  await page.goto('/?scenario=normal&aiccScenario=populated')
  await page.getByTestId('desktop-app-ai-center').click()
  await page.getByRole('button', { name: 'Providers', exact: true }).click()
  await page.getByRole('button', { name: 'Add Provider' }).click()
  await page.getByRole('button', { name: /Custom Provider/ }).click()
  await page.getByRole('button', { name: 'Next', exact: true }).click()
  await page.getByPlaceholder('custom-main').fill('custom-rules')
  await page.getByPlaceholder('sk-...').fill('mock-key')
  await page.getByRole('combobox', { name: /^Base URL/ }).fill('https://example.test/v1')
  await page.getByRole('combobox', { name: 'Protocol Family', exact: true }).selectOption('openai-responses')
  await page.getByRole('button', { name: 'Next', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Next', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Next', exact: true }).click()
  await page.getByRole('button', { name: 'Create Provider', exact: true }).click()
  await expect(page.getByRole('button', { name: /Est\. Cost/ })).toBeVisible()
  await page.getByRole('button', { name: 'Providers', exact: true }).click()
  await page.getByRole('button').filter({ hasText: 'custom-rules/custom' }).click()
  await page.getByRole('button', { name: 'Provider rules', exact: true }).click()
  const panel = page.getByRole('region', { name: 'Provider rules', exact: true })
  await expect(panel.getByTestId('provider-rule-model')).toHaveCount(2)
  await expect(page.getByRole('region', { name: 'Rules preview', exact: true })).toHaveCount(0)
  await panel.getByRole('searchbox', { name: 'Search model name' }).fill('CHAT')
  await expect(panel.getByTestId('provider-rule-model')).toHaveCount(1)
  await expect(panel.getByRole('button', { name: 'Edit rules', exact: true })).toBeEnabled()
  await panel.getByRole('button', { name: 'Edit rules', exact: true }).click()
  await panel.getByRole('button', { name: 'Configure', exact: true }).click()
  const editor = page.getByRole('region', { name: 'Model configuration', exact: true })
  const alias = editor.getByRole('combobox', { name: 'Mapped built-in model', exact: true })
  await alias.fill('openai/gpt-5.1')
  await alias.press('Tab')
  await editor.getByRole('combobox', { name: 'Select LLM tasks', exact: true }).click()
  await page.getByRole('option', { name: 'llm.chat', exact: true }).click()
  await editor.getByRole('combobox', { name: 'Select LLM tasks', exact: true }).press('Escape')
  await expect(editor.getByRole('combobox', { name: 'Adapter operation llm', exact: true })).toHaveValue('')
  await editor.getByText('Advanced request rules', { exact: true }).click()
  const requests = editor.getByRole('textbox', { name: 'request_rules · llm', exact: true })
  await requests.fill('[')
  await editor.getByRole('button', { name: 'Back to model list', exact: true }).click()
  await panel.getByRole('button', { name: 'Finish editing and apply' }).click()
  await expect(panel.getByRole('alert').first()).toBeVisible()
  await panel.getByRole('button', { name: 'Configure', exact: true }).click()
  await editor.getByText('Advanced request rules', { exact: true }).click()
  await requests.fill('[{"remove":["/temperature"]}]')
  await editor.getByRole('checkbox', { name: 'Enable effort low', exact: true }).check()
  await editor.getByRole('textbox', { name: 'provider_options · low', exact: true }).fill('{}')
  await editor.getByRole('checkbox', { name: 'Enable effort high', exact: true }).check()
  await editor.getByRole('textbox', { name: 'provider_options · high', exact: true }).fill('{')
  await editor.getByRole('checkbox', { name: 'Enable effort high', exact: true }).uncheck()
  await editor.getByRole('button', { name: 'Back to model list', exact: true }).click()
  const rowBox = await panel.getByTestId('provider-rule-model').boundingBox()
  expect(rowBox!.height).toBeLessThan(rowBox!.width < 980 ? 240 : 130)
  await panel.getByRole('button', { name: 'Full configuration JSON', exact: true }).click()
  const json = panel.getByLabel('Full configuration JSON', { exact: true })
  const draft = JSON.parse(await json.innerText())
  const model = draft.models.find((model: { id: string }) => model.id === 'custom-chat-model')
  expect(model.operations?.llm).toBeUndefined()
  expect(model.request_rules[0].when.api_type).toEqual(['llm'])
  expect(draft.model_variants).toBeUndefined()
  expect(draft.variants).toEqual([{
    model_driver: 'openai', variant: 'reasoning-low', match: { provider_model_id: 'custom-chat-model' }, provider_options: {},
  }])
  const downloadPromise = page.waitForEvent('download')
  await panel.getByRole('button', { name: 'Export full JSON' }).click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toMatch(/\.provider\.json$/)
  const stream = await download.createReadStream()
  const chunks: Buffer[] = []
  for await (const chunk of stream!) chunks.push(Buffer.from(chunk))
  const exported = JSON.parse(Buffer.concat(chunks).toString('utf8'))
  expect(exported.format).toBe('buckyos.aicc.provider-rules-catalog')
  expect(exported.instance_rules).toBeUndefined()
  expect(exported.server_default_routes['custom-chat-model']).toEqual(['llm.chat'])
  expect(JSON.stringify(exported)).not.toContain('mock-key')
  await page.evaluate(async () => {
    const modulePath = '/src/api/aicc_mgr.ts'
    const { AICCModelStore } = await import(/* @vite-ignore */ modulePath)
    const preview = AICCModelStore.prototype.previewProviderRules
    AICCModelStore.prototype.previewProviderRules = async function (...args: unknown[]) {
      AICCModelStore.prototype.previewProviderRules = preview
      await new Promise<void>((resolve) => { (globalThis as unknown as { releaseRulesImport: () => void }).releaseRulesImport = resolve })
      return preview.apply(this, args)
    }
  })
  await panel.getByRole('combobox', { name: 'Channel preset rules', exact: true }).selectOption('openrouter')
  await panel.getByRole('button', { name: 'Import built-in rules', exact: true }).click()
  await expect(panel.getByRole('button', { name: 'Importing...', exact: true })).toBeDisabled()
  await expect(panel.getByRole('button', { name: 'Finish editing and apply', exact: true })).toBeDisabled()
  await expect(panel.getByRole('button', { name: 'Saving...', exact: true })).toHaveCount(0)
  await page.evaluate(() => (globalThis as unknown as { releaseRulesImport: () => void }).releaseRulesImport())
  await expect(panel.getByRole('status')).toContainText('OpenRouter')
  await panel.getByRole('button', { name: 'Model list', exact: true }).click()
  await expect(panel.getByTestId('provider-rule-model')).toContainText('responses.create')
  await panel.getByRole('button', { name: 'Configure', exact: true }).click()
  await expect(editor.getByRole('combobox', { name: 'Adapter operation llm', exact: true })).toHaveValue('responses.create')
  await editor.getByRole('button', { name: 'Back to model list', exact: true }).click()
  await panel.getByRole('button', { name: 'Full configuration JSON', exact: true }).click()
  await panel.getByRole('combobox', { name: 'Channel preset rules', exact: true }).selectOption('deepseek')
  await panel.getByRole('button', { name: 'Import built-in rules', exact: true }).click()
  await expect(panel.getByRole('status')).toContainText('DeepSeek')
  const presetDraft = JSON.parse(await json.innerText())
  expect(presetDraft.provider_profile_id).toBe('deepseek')
  expect(presetDraft.model_driver_overrides['deepseek-flash']).toBe('deepseek/deepseek-v4.1-flash')
  await panel.getByRole('button', { name: 'Finish editing and apply' }).click()
  await expect(panel.getByRole('status')).toContainText('Rules applied')
  expect(JSON.parse(await json.innerText()).provider_profile_id).toBe('deepseek')
  await panel.getByRole('button', { name: 'Edit rules', exact: true }).click()
  exported.model_driver_overrides['custom-chat-model'] = 'openai/gpt-5.1-mini'
  await panel.getByLabel('Import full JSON', { exact: true }).setInputFiles({
    name: 'custom-rules.provider.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(exported)),
  })
  await expect(panel.getByRole('status')).toContainText('pending apply')
  await panel.getByRole('button', { name: 'Finish editing and apply' }).click()
  await expect(panel.getByRole('status')).toContainText('Rules applied')
  await expect(json).toContainText('openai/gpt-5.1-mini')
  await panel.getByRole('button', { name: 'Model list', exact: true }).click()
  await page.screenshot({ path: testInfo.outputPath('rules-list.png') })
  await page.setViewportSize({ width: 1920, height: 1080 })
  await page.getByTestId('window-ai-center').getByRole('button', { name: 'Maximize', exact: true }).click()
  await expect(panel.locator('thead')).toBeVisible()
  const wideRow = await panel.getByTestId('provider-rule-model').boundingBox()
  expect(wideRow!.height).toBeLessThan(130)
  const action = await panel.getByRole('button', { name: 'View parameters', exact: true }).boundingBox()
  expect(action!.x + action!.width).toBeLessThanOrEqual(wideRow!.x + wideRow!.width)
  await page.screenshot({ path: testInfo.outputPath('rules-list-wide.png') })
  await panel.getByRole('button', { name: 'View parameters', exact: true }).click()
  await expect(editor.getByRole('checkbox', { name: 'Enable effort low', exact: true })).toBeChecked()
  await page.screenshot({ path: testInfo.outputPath('rules-drawer.png') })
  await editor.getByRole('button', { name: 'Back to model list', exact: true }).click()
  await page.setViewportSize({ width: 375, height: 812 })
  await expect(page.getByRole('button', { name: 'Provider rules', exact: true })).toHaveCount(0)
  await expect(page.getByRole('region', { name: 'Provider rules', exact: true })).toHaveCount(0)
})
