test('FB-02: NFSP batches keep individual results, invalidate immediately and guard revisions', async ({ page }) => {
  await openFiles(page)
  const report = await page.evaluate(async () => {
    const { nfspClient } = await import('/src/app/filebrowser/data/nfsp/' + 'client.ts')
    const { registerNfspFolderOps } = await import('/src/app/filebrowser/data/nfsp/' + 'folderOps.ts')
    const { folderOps } = await import('/src/app/filebrowser/data/' + 'folderOps.ts')
    const { watchDfsPath } = await import('/src/app/filebrowser/data/nfsp/' + 'invalidation.ts')
    const calls: string[] = []
    const revisions: unknown[] = []
    const client = nfspClient()
    client.hello = async () => ({})
    client.stat = async (path: string, opts?: { name?: string }) => ({ ref: { type: 'live', node_id: opts?.name ?? path }, kind: opts?.name ? 'file' : 'dir', capabilities: { accepts_content: true }, revision: `revision:${path}` })
    client.delete = async (_path: string, name: string, options: unknown) => { calls.push(name); revisions.push(options); if (name === 'b') throw { code: 'PERMISSION_DENIED' } }
    const unwatch = watchDfsPath('/source', () => calls.push('invalidate'))
    registerNfspFolderOps()
    const entries = ['a','b','c'].map((name) => ({ id: name, name, path: `/source/${name}`, kind: 'document', modifiedAt: '2026-09-07T00:00:00Z' }))
    const results = await folderOps().deleteEntries(entries)
    const stale = await folderOps().deleteEntries([{ ...entries[0], id: 'replaced' }])
    client.stat = async () => { throw { code: 'PERMISSION_DENIED' } }
    let lookupError = ''
    try { await folderOps().nameExists('/source', 'a') } catch (err) { lookupError = (err as { code: string }).code }
    unwatch()
    return { calls, revisions, statuses: results.map((result: { status: string }) => result.status), stale: stale[0].error.code, lookupError }
  })
  expect(report.statuses).toEqual(['success', 'failed', 'success'])
  expect(report.calls).toEqual(['a', 'invalidate', 'b', 'c', 'invalidate'])
  expect(report.revisions).toEqual(Array(3).fill({ recursive: false, expectedRevision: 'revision:/source' }))
  expect(report.stale).toBe('STALE')
  expect(report.lookupError).toBe('PERMISSION_DENIED')
})

