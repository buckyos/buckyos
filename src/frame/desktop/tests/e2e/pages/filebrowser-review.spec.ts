import { expect, test, type Page } from '@playwright/test'

async function openFiles(page: Page, extra = '') {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto(`/?scenario=normal&fbData=mock${extra}`)
  await page.getByTestId('desktop-app-files').click()
  const win = page.getByTestId('window-files')
  await expect(win.getByRole('cell', { name: 'Documents', exact: true })).toBeVisible()
  return win
}
async function documents(page: Page) {
  const win = page.getByTestId('window-files')
  await win.locator('aside').first().getByRole('button', { name: 'Documents', exact: true }).click()
  await expect(win.getByRole('cell', { name: 'Kyoto Trip Plan.md', exact: true })).toBeVisible()
  return win
}
async function fixture(page: Page, entries: { id: string; name: string; path: string; kind?: string; sizeBytes?: number }[]) {
  await page.evaluate(async (entries) => {
    const data = await import('/src/app/filebrowser/mock/' + 'data.ts')
    const reader = await import('/src/app/filebrowser/data/' + 'mockReader.ts')
    for (const entry of entries) data.mockAddEntry({ kind: 'document', modifiedAt: '2026-09-07T00:00:00Z', ...entry })
    new Set(entries.map((entry) => entry.path.slice(0, entry.path.lastIndexOf('/')))).forEach((path) => reader.invalidateMockPath(path))
  }, entries)
}

