/* Builds ../presets.ts — DrawingML's 187 preset geometries as a table the guide interpreter (`../geometry.ts`) reads —
 * from ECMA-376 Part 1's `presetShapeDefinitions.xml` (Office 导入 TODO §2.1, O3). Each shape keeps its adjust
 * values (avLst), guides (gdLst) and paths (pathLst: w / h / fill / stroke and the commands with their operands as
 * written: numbers or guide names); connection sites and the text rectangle are not used by the importer.
 *
 *   deno run -A tools/presets.ts [presetShapeDefinitions.xml]
 *
 * Without an argument the file is fetched from Apache POI's repository (Apache-2.0), which carries it unchanged from
 * the standard. */

import { elements, parseXml, type XmlElement } from '../../import-drawio/xml.ts'

const SOURCE = 'https://raw.githubusercontent.com/apache/poi/trunk/poi/src/main/resources/org/apache/poi/sl/draw/geom/presetShapeDefinitions.xml'
const local = (n: string) => n.slice(n.indexOf(':') + 1)
const child = (el: XmlElement, name: string) => elements(el).find((c) => local(c.name) === name)

const text = Deno.args[0] ? await Deno.readTextFile(Deno.args[0]) : await (await fetch(SOURCE)).text()
const root = parseXml(text)
const table: Record<string, unknown> = {}
const guides = (el: XmlElement | undefined) => (el ? elements(el).filter((g) => local(g.name) === 'gd').map((g) => [g.attrs.name, g.attrs.fmla]) : [])
const pt = (el: XmlElement | undefined) => (el ? [el.attrs.x, el.attrs.y] : ['0', '0'])
const num = (v: string) => (/^-?\d+$/.test(v) ? Number(v) : v)
for (const shape of elements(root)) {
  const paths = []
  for (const path of elements(child(shape, 'pathLst') ?? { name: '', attrs: {}, children: [] })) {
    const cmds: unknown[] = []
    for (const c of elements(path)) {
      const pts = elements(c).filter((p) => local(p.name) === 'pt').map(pt).flat().map(num)
      switch (local(c.name)) {
        case 'moveTo': cmds.push(['M', ...pts]); break
        case 'lnTo': cmds.push(['L', ...pts]); break
        case 'quadBezTo': cmds.push(['Q', ...pts]); break
        case 'cubicBezTo': cmds.push(['C', ...pts]); break
        case 'arcTo': cmds.push(['A', num(c.attrs.wR), num(c.attrs.hR), num(c.attrs.stAng), num(c.attrs.swAng)]); break
        case 'close': cmds.push(['Z']); break
      }
    }
    const p: Record<string, unknown> = { cmds }
    if (path.attrs.w) p.w = Number(path.attrs.w)
    if (path.attrs.h) p.h = Number(path.attrs.h)
    if (path.attrs.fill && path.attrs.fill !== 'norm') p.fill = path.attrs.fill
    if (path.attrs.stroke === 'false' || path.attrs.stroke === '0') p.stroke = false
    paths.push(p)
  }
  table[local(shape.name)] = { av: guides(child(shape, 'avLst')), gd: guides(child(shape, 'gdLst')), paths }
}
const head = `/* DrawingML preset geometries (ECMA-376 Part 1, presetShapeDefinitions.xml) for the guide interpreter in
 * geometry.ts. Generated by tools/presets.ts — do not edit. ${Object.keys(table).length} shapes. */

import type { PresetDef } from './geometry.ts'

export const PRESETS: Record<string, PresetDef> = `
await Deno.writeTextFile(new URL('../presets.ts', import.meta.url), head + JSON.stringify(table) + '\n')
console.log(`${Object.keys(table).length} presets`)
